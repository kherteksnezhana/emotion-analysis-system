def get_last_working_days(count=20):
    """
    Возвращает список последних count рабочих дней (без субботы и воскресенья)
    Даты идут от самой старой к самой новой (для последовательного добавления)
    """
    working_days = []
    # Начинаем с вчерашнего дня, чтобы не включать сегодня
    current_date = datetime.now().replace(hour=15, minute=30, second=0) - timedelta(days=1)
    
    while len(working_days) < count:
        # Пропускаем субботу (5) и воскресенье (6)
        if current_date.weekday() not in [5, 6]:
            working_days.append(current_date)
        current_date -= timedelta(days=1)
    
    # Переворачиваем, чтобы самый старый отчёт был первым
    working_days.reverse()
    return working_days


